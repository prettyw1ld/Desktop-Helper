// Просьба «как сделать…» / «покажи…»: такую Пуш не объясняет текстом, а показывает на экране.
// Узнаём сами, без ИИ: модели часто игнорируют просьбу отвечать меткой и пишут шаги текстом.

const ACT = '(сдела|постав|включ|выключ|откр|закр|найт|найд|запуст|установ|удал|сохран|скача|загруз|отправ|напис|распечат|печат|настро|измен|помен|сменить|увелич|уменьш|подключ|отключ|позвон|добав|скопир|вставит|перенес|переимен|созда|завест|убра|выбра|посмотр|зайт|войт|выйт|вернут|свернут|разверн|обнов|почист|очист)';

// \b в JS не видит границ русских слов, поэтому границы через \p{L} с флагом u
const B = '(?<!\\p{L})';
const E = '(?!\\p{L})';
const re = (src: string) => new RegExp(src, 'iu');

const HOW_TO: RegExp[] = [
  re(`^\\s*(пожалуйста[,\\s]+)?(покажи|показать|научи|подскажи|объясни|расскажи|помоги)${E}`),
  re(`${B}как\\s+(мне\\s+|бы\\s+|же\\s+|можно\\s+|нужно\\s+|надо\\s+|это\\s+)*${ACT}`),
  re(`${B}(хочу|нужно|надо|помоги|не могу|не получается)\\s+(мне\\s+)?${ACT}`),
  re(`${B}где\\s+(найти|находится|взять|лежит|мои|мой|моя|у меня)${E}`),
  /^\s*(show me|teach me|help me)\b/i,
  /\bhow (do|can|to|should) (i|you|we)?\s*\w+/i,
  /\bwhere (is|are|do i find|can i find)\b/i,
];

// Разговор, а не задача на экране: «как дела», «как тебя зовут», «расскажи сказку».
const CHAT_ONLY = re(`${B}как\\s+(дела|ты|жизнь|настроение|тебя\\s+зовут|поживаешь)${E}|сказк|анекдот|шутк|стих|напомни|how are you|\\bjoke\\b|remind me`);

/** Похоже ли сообщение на просьбу показать, как что-то сделать на компьютере. */
export function isHowTo(text: string): boolean {
  const t = String(text || '').trim();
  if (t.length < 6 || CHAT_ONLY.test(t)) return false;
  return HOW_TO.some((re) => re.test(t));
}

/** «Покажи, пожалуйста, как поставить таймер?» → «поставить таймер» для цели показа. */
export function goalFromHowTo(text: string): string {
  const t = String(text || '').trim().replace(/[?!.…]+$/, '');
  // «…объясни, как поставить таймер» → всё после «как»
  const how = re(`${B}как\\s+(мне\\s+|бы\\s+|же\\s+|можно\\s+|нужно\\s+|надо\\s+)*`).exec(t);
  const cut = (how ? t.slice(how.index + how[0].length) : t)
    .replace(/^\s*(пожалуйста[,\s]+)?(покажи|показать|научи|подскажи|объясни|расскажи|помоги)(\s+мне)?[,\s]*(пожалуйста[,\s]*)?/i, '')
    .replace(re(`[,\\s]+(и\\s+)?(покажи|показать|пожалуйста)${E}.*$`), '')
    .trim();
  const goal = cut.length >= 4 ? cut : t;
  return goal.charAt(0).toUpperCase() + goal.slice(1);
}

/** «Как это сделать?» без самой задачи: цель надо брать из прошлых сообщений. */
export const vagueGoal = (goal: string): boolean =>
  re(`^(это|так|такое|то|его|её|ее|их)${E}|^(сделать|это сделать)${E}`).test(goal.trim()) || goal.trim().length < 6;
